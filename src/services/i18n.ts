export type TranslationKey = keyof typeof DICTIONARY.pt;

/**
 * Função utilitária para obter a tradução correspondente ao idioma ativo
 */
export function t(key: TranslationKey, lang: LanguageCode = 'pt'): string {
  const dict = DICTIONARY[lang] || DICTIONARY.pt;
  return dict[key] || DICTIONARY.pt[key] || key;
}

/**
 * Converte código de país em código de idioma correspondente
 */
export function countryToLanguage(country: CountryCode): LanguageCode {
  return country === 'ES' ? 'es' : 'pt';
}

/**
 * Converte código de idioma em código de país padrão
 */
export function languageToCountry(language: LanguageCode): CountryCode {
  return language === 'es' ? 'ES' : 'PT';
}
